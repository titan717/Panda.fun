import { chromium } from "playwright";
const state = { profiles: [{ id: "p1", name: "You", avatar: "smile", kids: false, createdAt: 1 }], activeProfileId: "p1", prefs: {}, data: {} };
const b = await chromium.launch({ args: ["--autoplay-policy=no-user-gesture-required"] });
const ctx = await b.newContext({ viewport: { width: 1920, height: 1080 } });
await ctx.addInitScript((s) => { localStorage.setItem("panda:v1:state", s); sessionStorage.setItem("panda:splash", "1"); }, JSON.stringify(state));
const p = await ctx.newPage(); const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
await p.goto("http://127.0.0.1:4173/profiles?layout=tv", { waitUntil: "networkidle" });
await p.waitForTimeout(1500);
const t0 = Date.now();
await p.keyboard.press("Enter");
await p.waitForTimeout(250); await p.screenshot({ path: "/tmp/qa/flow-zoom.png" });
await p.waitForURL((u) => !u.pathname.startsWith("/profiles"), { timeout: 5000 });
await p.waitForSelector(".tv-hero-card", { timeout: 8000 });
console.log("home in", Date.now() - t0, "ms");
await p.waitForTimeout(1500); await p.screenshot({ path: "/tmp/qa/flow-home.png" });
await p.waitForTimeout(6500);
console.log("iframe", await p.locator(".tv-hero iframe").count(), "trailer class", await p.locator(".tv-hero.is-trailer").count());
await p.screenshot({ path: "/tmp/qa/flow-trailer.png" });
await p.keyboard.press("ArrowDown"); await p.waitForTimeout(700);
console.log("after move iframe", await p.locator(".tv-hero iframe").count());
await p.screenshot({ path: "/tmp/qa/flow-row.png" });
await p.waitForTimeout(8000);
console.log("row trailer", await p.locator(".tv-backdrop iframe").count(), await p.locator(".tv-home.is-row-trailer").count());
await p.screenshot({ path: "/tmp/qa/flow-rowtrailer.png" });
console.log(errs.join("\n") || "NO ERRORS"); await b.close();
